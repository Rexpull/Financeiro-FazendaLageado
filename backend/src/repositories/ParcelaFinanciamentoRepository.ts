import { ParcelaFinanciamento } from "../models/ParcelaFinanciamento";
import { hojeISO } from "../utils/relatorioFinanciamentos";
import { RegistroEmUsoError, juntarLista, plural } from "../utils/verificarUsoRegistro";

export class ParcelaFinanciamentoRepository {
	private db: D1Database;

	constructor(db: D1Database) {
		this.db = db;
	}

	async getAll(): Promise<ParcelaFinanciamento[]> {
		const { results } = await this.db.prepare(`
			SELECT id, idMovimentoBancario, valor, dt_vencimento, numParcela
			FROM parcelaFinanciamento
		`).all();

		return results.map(result => ({
			id: result.id as number,
			idMovimentoBancario: result.idMovimentoBancario as number,
			valor: result.valor as number,
			dt_vencimento: result.dt_vencimento as string,
			numParcela: result.numParcela as number
		})) as ParcelaFinanciamento[];
	}

	async getByAno(ano: string): Promise<ParcelaFinanciamento[]> {
		const inicio = `${ano}-01-01`;
		const fim = `${ano}-12-31`;
	
		const { results } = await this.db.prepare(`
			SELECT * FROM ParcelaFinanciamento
			WHERE dt_vencimento BETWEEN ? AND ?
		`).bind(inicio, fim).all();
	
		return results.map(result => ({
			id: result.id as number,
			idMovimentoBancario: result.idMovimentoBancario as number,
			idFinanciamento: result.idFinanciamento as number,
			valor: result.valor as number,
			status: result.status as 'Aberto' | 'Vencido' | 'Liquidado',
			dt_vencimento: result.dt_vencimento as string,
			dt_liquidacao: result.dt_liquidacao as string | null,
			numParcela: result.numParcela as number
		})) as ParcelaFinanciamento[];
	}

	async getParcelasDoAno(ano: string): Promise<ParcelaFinanciamento[]> {
		const { results } = await this.db
			.prepare(
				`
		  SELECT * FROM ParcelaFinanciamento
		  WHERE STRFTIME('%Y', COALESCE(dt_liquidacao, dt_vencimento)) = ?
		`
			)
			.bind(ano)
			.all();

		return results.map((p) => ({
			id: p.id as number,
			idMovimentoBancario: p.idMovimentoBancario as number | null,
			idFinanciamento: p.idFinanciamento as number,
			valor: p.valor as number,
			status: p.status as 'Aberto' | 'Vencido' | 'Liquidado',
			numParcela: p.numParcela as number,
			dt_lancamento: p.dt_lancamento as string,
			dt_vencimento: p.dt_vencimento as string,
			dt_liquidacao: p.dt_liquidacao as string | null,
		})) as ParcelaFinanciamento[];
	}
	

	async getByIdMovimentoBancario(idMovimentoBancario: number): Promise<ParcelaFinanciamento[]> {
		const { results } = await this.db.prepare(`
		  SELECT id, idMovimentoBancario, valor, dt_vencimento, numParcela
		  FROM parcelaFinanciamento
		  WHERE idMovimentoBancario = ?
		`).bind(idMovimentoBancario).all();
	
		return results.map(result => ({
		  id: result.id as number,
		  idMovimentoBancario: result.idMovimentoBancario as number,
		  valor: result.valor as number,
		  dt_vencimento: result.dt_vencimento as string,
		  numParcela: result.numParcela as number
		})) as ParcelaFinanciamento[];
	  }

	async getByIdFinanciamento(idFinanciamento: number): Promise<ParcelaFinanciamento[]> {
		const { results } = await this.db.prepare(`
			SELECT * FROM parcelaFinanciamento
			WHERE idFinanciamento = ?
			ORDER BY numParcela
		`).bind(idFinanciamento).all();

		return results.map((p) => ({
			id: p.id as number,
			idMovimentoBancario: p.idMovimentoBancario as number | null,
			idFinanciamento: p.idFinanciamento as number,
			valor: p.valor as number,
			status: p.status as 'Aberto' | 'Vencido' | 'Liquidado',
			numParcela: p.numParcela as number,
			dt_lancamento: p.dt_lancamento as string,
			dt_vencimento: p.dt_vencimento as string,
			dt_liquidacao: p.dt_liquidacao as string | null,
		})) as ParcelaFinanciamento[];
	}

	/**
	 * Statements that detach parcelas from bank movements that are about to be deleted or have their
	 * conciliação cleared. A financing installment is NEVER deleted with a movement:
	 * - paid by the movement (Liquidado) → reopened: Vencido if past due (São Paulo calendar day),
	 *   else Aberto; dt_liquidacao and idMovimentoBancario cleared;
	 * - merely generated by / linked to it → only unlinked (idMovimentoBancario = NULL).
	 * Run them in the SAME db.batch as the movement change (one transaction), before the DELETE
	 * (parcelaFinanciamento.idMovimentoBancario is a foreign key). At most 98 ids per call (D1 binds).
	 */
	statementsDesvincularMovimentos(idsMovimentos: number[], hoje: string = hojeISO()): D1PreparedStatement[] {
		if (idsMovimentos.length === 0) return [];
		const placeholders = idsMovimentos.map(() => '?').join(',');
		return [
			this.db
				.prepare(
					`UPDATE parcelaFinanciamento
					 SET status = CASE WHEN date(dt_vencimento) < date(?) THEN 'Vencido' ELSE 'Aberto' END,
						 dt_liquidacao = NULL,
						 idMovimentoBancario = NULL
					 WHERE idMovimentoBancario IN (${placeholders}) AND status = 'Liquidado'`,
				)
				.bind(hoje, ...idsMovimentos),
			this.db
				.prepare(`UPDATE parcelaFinanciamento SET idMovimentoBancario = NULL WHERE idMovimentoBancario IN (${placeholders})`)
				.bind(...idsMovimentos),
		];
	}

	/**
	 * Throws RegistroEmUsoError (409) when the parcela is liquidated, linked to a bank movement or
	 * referenced by Resultado rows: deleting it would rewrite the contract history (saldo devedor,
	 * relatório, Caixa) or fail on the Resultado foreign key.
	 */
	async assertPodeExcluir(id: number): Promise<void> {
		const [parcelaRes, resultadoRes] = await this.db.batch([
			this.db.prepare(`SELECT numParcela, status, idMovimentoBancario FROM parcelaFinanciamento WHERE id = ?`).bind(id),
			this.db.prepare(`SELECT COUNT(*) AS n FROM Resultado WHERE idParcelaFinanciamento = ?`).bind(id),
		]);
		const parcela = parcelaRes.results?.[0] as { numParcela: number; status: string; idMovimentoBancario: number | null } | undefined;
		if (!parcela) return;
		const nResultados = Number((resultadoRes.results?.[0] as { n?: number } | undefined)?.n ?? 0);
		const motivos: string[] = [];
		if (parcela.status === 'Liquidado') motivos.push('está liquidada');
		if (parcela.idMovimentoBancario != null) motivos.push('está vinculada a um lançamento bancário');
		if (nResultados > 0) {
			motivos.push(`tem ${plural(nResultados, 'lançamento de resultado vinculado', 'lançamentos de resultado vinculados')}`);
		}
		if (motivos.length > 0) {
			throw new RegistroEmUsoError(
				`Não é possível excluir a parcela ${parcela.numParcela}: ela ${juntarLista(motivos)}. ` +
					'Estorne a liquidação ou exclua/limpe a conciliação do lançamento antes de excluir a parcela.',
			);
		}
	}

	async create(parcela: ParcelaFinanciamento): Promise<number> {
		try {
			const {
				idMovimentoBancario = null,
				idFinanciamento,
				valor,
				status,
				numParcela,
				dt_lancamento,
				dt_vencimento,
				dt_liquidacao = null
			} = parcela;

			console.log("Dados da parcela para inserção:", {
				idMovimentoBancario,
				idFinanciamento,
				valor,
				status,
				numParcela,
				dt_lancamento,
				dt_vencimento,
				dt_liquidacao
			});

			const bindValues = [
				idMovimentoBancario, idFinanciamento, valor, status,
				numParcela, dt_lancamento, dt_vencimento, dt_liquidacao
			];

			// Verificar se há valores undefined no array
			const hasUndefined = bindValues.some(value => value === undefined);
			if (hasUndefined) {
				console.error('❌ Valores undefined detectados no bindValues da ParcelaFinanciamento:', bindValues);
				throw new Error('Valores undefined não são suportados pelo D1 Database');
			}

			const { meta } = await this.db.prepare(`
				INSERT INTO parcelaFinanciamento (
					idMovimentoBancario, idFinanciamento, valor, status,
					numParcela, dt_lancamento, dt_vencimento, dt_liquidacao
				)
				VALUES (?, ?, ?, ?, ?, ?, ?, ?)
			`).bind(...bindValues).run();

			return meta.last_row_id;
		} catch (error) {
			console.error("Erro ao criar parcela:", error);
			throw new Error(`Erro ao criar parcela: ${error instanceof Error ? error.message : "Erro desconhecido"}`);
		}
	}

	async update(id: number, parcela: ParcelaFinanciamento): Promise<void> {
		const { 
			idMovimentoBancario, 
			valor, 
			dt_vencimento, 
			numParcela,
			status,
			dt_liquidacao
		} = parcela;

		const bindValues = [
			idMovimentoBancario, 
			valor, 
			dt_vencimento, 
			numParcela,
			status,
			dt_liquidacao,
			id
		];

		// Verificar se há valores undefined no array
		const hasUndefined = bindValues.some(value => value === undefined);
		if (hasUndefined) {
			console.error('❌ Valores undefined detectados no bindValues da ParcelaFinanciamento update:', bindValues);
			throw new Error('Valores undefined não são suportados pelo D1 Database');
		}

		await this.db.prepare(`
			UPDATE parcelaFinanciamento
			SET idMovimentoBancario = ?, 
				valor = ?, 
				dt_vencimento = ?, 
				numParcela = ?,
				status = ?,
				dt_liquidacao = ?
			WHERE id = ?
		`).bind(...bindValues).run();
	}

	/** Refuses (RegistroEmUsoError → 409) parcelas in use; see assertPodeExcluir. */
	async deleteById(id: number): Promise<void> {
		await this.assertPodeExcluir(id);
		await this.db.prepare(`DELETE FROM parcelaFinanciamento WHERE id = ?`).bind(id).run();
	}
}
