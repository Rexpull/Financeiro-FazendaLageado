/** Codifica texto (code points <= 0xFF, sem 0x80–0x9F) como bytes windows-1252/latin1. */
export function toSingleByte(text: string): Uint8Array {
  return Uint8Array.from(text, (ch) => {
    const code = ch.charCodeAt(0);
    if (code > 0xff) throw new Error(`caractere fora de latin1: ${ch}`);
    return code;
  });
}

