function linhaOfx(opts: { fitid: string; valor: number; historico: string; conta: number }) {
	const identificadorOfx = `${opts.fitid}|${DT}|${opts.valor.toFixed(2)}`;
	return {
		dtMovimento: DT,
		historico: opts.historico,
		valor: opts.valor,
		saldo: 0,
		idContaCorrente: opts.conta,
		identificadorOfx,
		numeroDocumento: identificadorOfx,
		tipoMovimento: opts.valor >= 0 ? 'C' : 'D',
		modalidadeMovimento: 'padrao',
		ideagro: false,
		parcelado: false,
	};
}

async function postBatch(movimentos: unknown[]) {
	const res = await request('POST', '/api/movBancario/batch', { movimentos });
	expect(res.status).toBe(200);
	return res.json as { novos: number; existentes: number; erros: number; movimentos: Array<{ id: number; identificadorOfx: string }> };
}

async function mb(id: number) {
	return db
		.prepare(`SELECT id, idContaCorrente, identificador_ofx FROM MovimentoBancario WHERE id = ?`)
		.bind(id)
		.first<{ id: number; idContaCorrente: number; identificador_ofx: string }>();
}

async function criarHistorico(id: number, idMovimentos: number[], conta: number) {
	await db
		.prepare(
			`INSERT INTO HistoricoImportacaoOFX (id, idUsuario, nomeArquivo, dataImportacao, idMovimentos, totalizadores,
			 novosMovimentos, existentesMovimentos, idContaCorrente, criadoEm, atualizadoEm)
			 VALUES (?, 1, 'extrato.ofx', '2026-10-05T12:00:00.000Z', ?, '{}', ?, 0, ?, '2026-10-05', '2026-10-05')`,
		)
		.bind(id, JSON.stringify(idMovimentos), idMovimentos.length, conta)
		.run();
}

async function historico(id: number) {
	const row = await db
		.prepare(`SELECT idContaCorrente, idMovimentos FROM HistoricoImportacaoOFX WHERE id = ?`)
		.bind(id)
		.first<{ idContaCorrente: number; idMovimentos: string }>();
	return row ? { idContaCorrente: row.idContaCorrente, idMovimentos: JSON.parse(row.idMovimentos) as number[] } : null;
}

describe('Item 3 — "Editar conta" of an OFX import (update-conta-ofx)', () => {
	beforeAll(async () => {
		await applySchema();
		await seed();
	});

	const L1 = { fitid: 'A1', valor: -100, historico: 'TARIFA' };
	const L2 = { fitid: 'A2', valor: -200, historico: 'PIX ENVIADO' };
	const L3 = { fitid: 'A3', valor: 300, historico: 'PIX RECEBIDO' };

	async function importarNa24() {
		const out = await postBatch([L1, L2, L3].map((l) => linhaOfx({ ...l, conta: 24 })));
		const [m1, m2, m3] = out.movimentos.map((m) => m.id);
		// L2 was ALSO imported (correctly) in account 25
		const dup = await postBatch([linhaOfx({ ...L2, conta: 25 })]);
		const m2na25 = dup.movimentos[0].id;
		// m1 classified → Resultado on account 24
		expect((await request('PUT', `/api/movBancario/${m1}`, { idPlanoContas: 300 })).status).toBe(200);
		await criarHistorico(1, [m1, m2, m3], 24);
		return { m1, m2, m3, m2na25 };
	}

	it('moves movements + Resultado + history, skipping lines the destination already has', async () => {
		const { m1, m2, m3, m2na25 } = await importarNa24();
		const res = await request('PATCH', '/api/movBancario/update-conta-ofx', {
			idMovimentos: [m1, m2, m3],
			novaContaId: 25,
			idHistorico: 1,
		});
		expect(res.status).toBe(200);
		expect(res.json).toMatchObject({ atualizados: 2, duplicados: 1, falhas: 0 });
		expect(res.json.movimentosDuplicados).toEqual([expect.objectContaining({ id: m2, idExistente: m2na25 })]);

		expect((await mb(m1))!.idContaCorrente).toBe(25);
		expect((await mb(m3))!.idContaCorrente).toBe(25);
		expect((await mb(m2))!.idContaCorrente).toBe(24); // skipped: never a duplicate in 25
		expect(await contar(`SELECT COUNT(*) n FROM Resultado WHERE idMovimentoBancario = ? AND idContaCorrente = 25`, m1)).toBe(1);
		expect(await contar(`SELECT COUNT(*) n FROM Resultado WHERE idContaCorrente = 24 AND idMovimentoBancario = ?`, m1)).toBe(0);

		expect(await historico(1)).toEqual({ idContaCorrente: 25, idMovimentos: [m1, m2na25, m3] });

		// per-account dedupe still works after the move
		expect(await postBatch([L1, L2, L3].map((l) => linhaOfx({ ...l, conta: 25 })))).toMatchObject({ novos: 0, existentes: 3 });
		expect(await contar(`SELECT COUNT(*) n FROM MovimentoBancario WHERE idContaCorrente = 25`)).toBe(3);
	});

	it('keeps identificadores unique per account (|@c<conta> suffix follows the destination)', async () => {
		const L4 = { fitid: 'A4', valor: -400, historico: 'BOLETO' };
		const na26 = (await postBatch([linhaOfx({ ...L4, conta: 26 })])).movimentos[0].id;
		const na24 = (await postBatch([linhaOfx({ ...L4, conta: 24 })])).movimentos[0].id;
		const base = linhaOfx({ ...L4, conta: 24 }).identificadorOfx;
		expect((await mb(na24))!.identificador_ofx).toBe(`${base}|@c24`);

		const res = await request('PATCH', '/api/movBancario/update-conta-ofx', { idMovimentos: [na24], novaContaId: 25 });
		expect(res.status).toBe(200);
		expect(res.json).toMatchObject({ atualizados: 1, duplicados: 0, falhas: 0 });
		expect(await mb(na24)).toMatchObject({ idContaCorrente: 25, identificador_ofx: `${base}|@c25` });
		expect((await mb(na26))!.identificador_ofx).toBe(base);

		expect(await postBatch([linhaOfx({ ...L4, conta: 25 })])).toMatchObject({ novos: 0, existentes: 1 });
		expect(await postBatch([linhaOfx({ ...L4, conta: 26 })])).toMatchObject({ novos: 0, existentes: 1 });
		// account 24 no longer has the line: importing it there creates it again
		expect(await postBatch([linhaOfx({ ...L4, conta: 24 })])).toMatchObject({ novos: 1, existentes: 0 });
	});

	it('reports failures instead of swallowing them; each movement moves with its Resultado or not at all', async () => {
		const { m1, m2, m3 } = await importarNa24();
		await db
			.prepare(
				`CREATE TRIGGER bloqueia_update_resultado BEFORE UPDATE ON Resultado WHEN OLD.idMovimentoBancario = ${m1}
				 BEGIN SELECT RAISE(ABORT, 'bloqueado'); END`,
			)
			.run();
		const res = await request('PATCH', '/api/movBancario/update-conta-ofx', {
			idMovimentos: [m1, m2, m3],
			novaContaId: 26,
			idHistorico: 1,
		});
		expect(res.status).toBe(500);
		expect(res.json).toMatchObject({ atualizados: 2, duplicados: 0, falhas: 1 });
		expect(typeof res.json.error).toBe('string');
		expect(res.json.detalhesFalhas.join(' ')).toMatch(String(m1));
		// m1 stays entirely on account 24 (movement AND Resultado)
		expect((await mb(m1))!.idContaCorrente).toBe(24);
		expect(await contar(`SELECT COUNT(*) n FROM Resultado WHERE idMovimentoBancario = ? AND idContaCorrente = 24`, m1)).toBe(1);
		expect((await mb(m2))!.idContaCorrente).toBe(26);
		expect((await mb(m3))!.idContaCorrente).toBe(26);
		// history only follows when everything moved (a retry finishes the job)
		expect((await historico(1))!.idContaCorrente).toBe(24);
	});
});

