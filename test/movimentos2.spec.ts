// Integration tests (round 2): data safety of bank-movement deletes, parcela deletes,
// "Editar conta" of an OFX import and the saldo route, against an isolated local D1
// seeded with the production schema snapshot. Storage is isolated per test.
import { env, SELF } from 'cloudflare:test';
import { describe, it, expect, beforeAll } from 'vitest';
import schemaSql from './fixtures/schema.sql?raw';

const BASE = 'https://worker.test';
const db = (env as unknown as { DB: D1Database }).DB;
const DT = '2026-10-05T00:00:00.000Z';

async function applySchema() {
	const statements = schemaSql
		.split(/;\s*\n/)
		.map((s) => s.replace(/^\s*--.*$/gm, '').trim())
		.filter(Boolean);
	for (const sql of statements) {
		await db.prepare(sql).run();
	}
}

