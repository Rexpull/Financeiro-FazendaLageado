describe('Item 2 — DELETE /api/parcelaFinanciamento/:id refuses parcelas in use', () => {
	beforeAll(async () => {
		await applySchema();
		await seed();
	});

	it('liquidated parcela → 409 with a Portuguese message', async () => {
		await cenarioParcelas();
		const res = await request('DELETE', '/api/parcelaFinanciamento/8');
		expect(res.status).toBe(409);
		expect(res.json.error).toMatch(/liquidada/);
		expect(await parcela(8)).not.toBeNull();
	});

	it('parcela linked to a bank movement → 409', async () => {
		await cenarioParcelas();
		const res = await request('DELETE', '/api/parcelaFinanciamento/7');
		expect(res.status).toBe(409);
		expect(res.json.error).toMatch(/lançamento bancário/);
		expect(await parcela(7)).not.toBeNull();
	});

	it('parcela referenced by Resultado → 409 (not a raw D1_ERROR 500)', async () => {
		await cenarioParcelas();
		await db.prepare(`UPDATE parcelaFinanciamento SET status = 'Aberto', idMovimentoBancario = NULL, dt_liquidacao = NULL WHERE id = 5`).run();
		const res = await request('DELETE', '/api/parcelaFinanciamento/5');
		expect(res.status).toBe(409);
		expect(res.json.error).toMatch(/resultado/);
		expect(JSON.stringify(res.json)).not.toMatch(/D1_ERROR/);
		expect(await parcela(5)).not.toBeNull();
	});

	it('free parcela is deleted', async () => {
		await cenarioParcelas();
		const res = await request('DELETE', '/api/parcelaFinanciamento/9');
		expect(res.status).toBe(200);
		expect(await parcela(9)).toBeNull();
	});
});

