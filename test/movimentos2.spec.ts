async function request(method: string, path: string, body?: unknown) {
	const res = await SELF.fetch(`${BASE}${path}`, {
		method,
		headers: { 'Content-Type': 'application/json' },
		body: body === undefined ? undefined : JSON.stringify(body),
	});
	const text = await res.text();
	let json: any = null;
	try {
		json = JSON.parse(text);
	} catch {
		json = text;
	}
	return { status: res.status, json };
}

async function inserirMovimento(id: number, opts: { conta?: number; valor?: number; modalidade?: string; idFinanciamento?: number | null; doc?: string } = {}) {
	await db
		.prepare(
			`INSERT INTO MovimentoBancario (id, dtMovimento, historico, idContaCorrente, valor, saldo, identificador_ofx, numero_documento,
			 tipoMovimento, modalidadeMovimento, idFinanciamento, idPlanoContas)
			 VALUES (?, '2026-10-05T00:00:00.000Z', ?, ?, ?, 0, ?, ?, ?, ?, ?, ?)`,
		)
		.bind(
			id,
			`mov ${id}`,
			opts.conta ?? 24,
			opts.valor ?? -1000,
			`ofx-${id}`,
			opts.doc ?? `DOC-${id}`,
			(opts.valor ?? -1000) >= 0 ? 'C' : 'D',
			opts.modalidade ?? 'financiamento',
			opts.idFinanciamento === undefined ? 1 : opts.idFinanciamento,
			opts.modalidade === 'padrao' ? 300 : null,
		)
		.run();
}

type ParcelaRow = {
	id: number;
	status: string;
	idMovimentoBancario: number | null;
	dt_liquidacao: string | null;
	valor: number;
};

async function inserirParcela(
	id: number,
	opts: { status: string; venc: string; idMov?: number | null; liquidacao?: string | null; num?: number },
) {
	await db
		.prepare(
			`INSERT INTO parcelaFinanciamento (id, idMovimentoBancario, idFinanciamento, valor, status, numParcela, dt_vencimento, dt_liquidacao)
			 VALUES (?, ?, 1, 1000, ?, ?, ?, ?)`,
		)
		.bind(id, opts.idMov ?? null, opts.status, opts.num ?? id, opts.venc, opts.liquidacao ?? null)
		.run();
}

async function parcela(id: number) {
	return db
		.prepare(`SELECT id, status, idMovimentoBancario, dt_liquidacao, valor FROM parcelaFinanciamento WHERE id = ?`)
		.bind(id)
		.first<ParcelaRow>();
}

async function contar(sql: string, ...binds: unknown[]) {
	return Number(await db.prepare(sql).bind(...binds).first('n'));
}

/**
 * Movement 100 (account 24) paid parcelas 5 (past due) and 6 (future); parcela 7 was merely
 * generated by it (still open). Movement 101 (account 24) paid parcela 8. A Resultado row of
 * movement 100 points at parcela 5.
 */
async function cenarioParcelas() {
	await inserirMovimento(100);
	await inserirMovimento(101);
	await inserirParcela(5, { status: 'Liquidado', venc: '2025-05-10', idMov: 100, liquidacao: '2025-05-10' });
	await inserirParcela(6, { status: 'Liquidado', venc: '2099-06-10', idMov: 100, liquidacao: '2026-10-05' });
	await inserirParcela(7, { status: 'Aberto', venc: '2099-07-10', idMov: 100 });
	await inserirParcela(8, { status: 'Liquidado', venc: '2025-08-10', idMov: 101, liquidacao: '2025-08-10' });
	await inserirParcela(9, { status: 'Aberto', venc: '2099-09-10' });
	await db
		.prepare(
			`INSERT INTO Resultado (dtMovimento, idMovimentoBancario, idPlanoContas, idContaCorrente, idParcelaFinanciamento, valor, tipo)
			 VALUES ('2026-10-05', 100, 310, 24, 5, 1000, 'D')`,
		)
		.run();
}

function esperaReaberta(p: ParcelaRow | null, status: 'Vencido' | 'Aberto') {
	expect(p).not.toBeNull();
	expect(p).toMatchObject({ status, idMovimentoBancario: null, dt_liquidacao: null });
}

